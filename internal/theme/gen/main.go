// Command gen emits web/src/styles/tokens.generated.css from the single
// source of truth in package theme. It is invoked via `go generate
// ./internal/theme/...` (see the //go:generate directive in palette.go).
//
// The output is a build artifact (gitignored) — never edit it by hand. Each
// built-in theme becomes one `html[data-theme="<name>"]` block of CSS custom
// properties; the web app selects a theme by setting that attribute.
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"runtime"
	"strings"

	"github.com/cnjack/jcode/internal/theme"
)

func main() {
	out := outputPath()

	var b strings.Builder
	b.WriteString("/* Code generated by internal/theme/gen; DO NOT EDIT. */\n")
	b.WriteString("/* Source of truth: internal/theme/palette.go — run `go generate ./internal/theme/...`. */\n\n")

	for _, t := range theme.All() {
		fmt.Fprintf(&b, "/* %s (%s) */\n", t.DisplayName, t.Appearance)
		fmt.Fprintf(&b, "html[data-theme=%q] {\n", t.Name)
		for _, v := range t.CSSVariables() {
			fmt.Fprintf(&b, "  %s: %s;\n", v.Name, v.Value)
		}
		b.WriteString("}\n\n")
	}

	if err := os.WriteFile(out, []byte(b.String()), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "theme/gen: write %s: %v\n", out, err)
		os.Exit(1)
	}
	fmt.Printf("theme/gen: wrote %d themes to %s\n", len(theme.All()), out)
}

// outputPath resolves web/src/styles/tokens.generated.css relative to this
// source file, so it works regardless of the caller's working directory.
func outputPath() string {
	_, file, _, ok := runtime.Caller(0)
	if !ok {
		fmt.Fprintln(os.Stderr, "theme/gen: cannot resolve source path")
		os.Exit(1)
	}
	// file = <repo>/internal/theme/gen/main.go → repo root is three levels up.
	repoRoot := filepath.Join(filepath.Dir(file), "..", "..", "..")
	return filepath.Join(repoRoot, "web", "src", "styles", "tokens.generated.css")
}
