// Command gen emits the web theme artifacts from the single source of truth in
// package theme. It is invoked via `go generate ./internal/theme/...` (see the
// //go:generate directive in palette.go).
//
// Two files are generated (both build artifacts, gitignored — never edit by
// hand):
//   - web/src/styles/tokens.generated.css : one [data-theme="<name>"] block
//     of CSS custom properties per theme.
//   - web/src/lib/themes.generated.ts : the theme registry (id, label,
//     appearance) the picker UI iterates, so the list can't drift either.
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"runtime"
	"strings"

	"github.com/cnjack/jcode/internal/theme"
)

func main() {
	writeFile(repoPath("web", "src", "styles", "tokens.generated.css"), css())
	writeFile(repoPath("web", "src", "lib", "themes.generated.ts"), ts())
	fmt.Printf("theme/gen: wrote %d themes (css + ts)\n", len(theme.All()))
}

func css() string {
	var b strings.Builder
	b.WriteString("/* Code generated by internal/theme/gen; DO NOT EDIT. */\n")
	b.WriteString("/* Source of truth: internal/theme/palette.go — run `go generate ./internal/theme/...`. */\n\n")
	for _, t := range theme.All() {
		fmt.Fprintf(&b, "/* %s (%s) */\n", t.DisplayName, t.Appearance)
		// Bare attribute selector (not html[...]) so the tokens can be scoped to
		// any element — e.g. a swatch card in the theme picker — not just :root.
		fmt.Fprintf(&b, "[data-theme=%q] {\n", t.Name)
		for _, v := range t.CSSVariables() {
			fmt.Fprintf(&b, "  %s: %s;\n", v.Name, v.Value)
		}
		b.WriteString("}\n\n")
	}
	return b.String()
}

func ts() string {
	var b strings.Builder
	b.WriteString("/* Code generated by internal/theme/gen; DO NOT EDIT. */\n")
	b.WriteString("/* Source of truth: internal/theme/palette.go — run `go generate ./internal/theme/...`. */\n\n")
	b.WriteString("export interface ThemeDef {\n")
	b.WriteString("  id: string\n")
	b.WriteString("  label: string\n")
	b.WriteString("  appearance: 'light' | 'dark'\n")
	b.WriteString("}\n\n")
	b.WriteString("export const THEMES: ThemeDef[] = [\n")
	for _, t := range theme.All() {
		fmt.Fprintf(&b, "  { id: %q, label: %q, appearance: %q },\n", t.Name, t.DisplayName, t.Appearance)
	}
	b.WriteString("]\n")
	return b.String()
}

func writeFile(path, content string) {
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "theme/gen: write %s: %v\n", path, err)
		os.Exit(1)
	}
}

// repoPath joins the given path elements onto the repo root, resolved relative
// to this source file so it works regardless of the caller's working directory.
func repoPath(elem ...string) string {
	_, file, _, ok := runtime.Caller(0)
	if !ok {
		fmt.Fprintln(os.Stderr, "theme/gen: cannot resolve source path")
		os.Exit(1)
	}
	// file = <repo>/internal/theme/gen/main.go → repo root is three levels up.
	repoRoot := filepath.Join(filepath.Dir(file), "..", "..", "..")
	return filepath.Join(append([]string{repoRoot}, elem...)...)
}
