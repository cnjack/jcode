#!/usr/bin/env node
/*
 * generate-compat-css — derives dist/compat.css from src/styles/tokens.css.
 *
 * compat.css keeps the pre-0.2 unprefixed token names working: every scoped
 * `--jcode-*` token is redeclared as `var(--<legacy name>, <default>)`, so a
 * host that still themes via `--color-primary` etc. (jcode web generated
 * themes, early adopters) keeps theming the components. Import order:
 *
 *   import 'jcode-ui/styles.css'
 *   import 'jcode-ui/compat.css'   // AFTER styles.css so it wins the cascade
 *
 * Tokens that were always public under `--jcode-*` (col-max, col-pad-x,
 * gutter) are skipped — their name did not change.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const pkgRoot = join(dirname(fileURLToPath(import.meta.url)), '..')
const src = readFileSync(join(pkgRoot, 'src/styles/tokens.css'), 'utf8')

/** Names that never had an unprefixed alias. */
const SKIP = new Set(['col-max', 'col-pad-x', 'gutter'])

const LIGHT_SEL = '[data-jcode-ui]'
const DARK_SEL = '.dark [data-jcode-ui],\n[data-jcode-ui].dark'

/** Collect `--jcode-x: value;` declarations per top-level block. */
function collectBlocks(css) {
  // Block comments may contain braces (inline examples) — strip them first.
  css = css.replace(/\/\*[\s\S]*?\*\//g, '')
  const blocks = []
  const re = /([^{}]+)\{([^{}]*)\}/g
  let m
  while ((m = re.exec(css))) {
    const selector = m[1].trim()
    const decls = []
    const declRe = /--jcode-([a-z0-9-]+):\s*([^;]+);/g
    let d
    while ((d = declRe.exec(m[2]))) {
      decls.push({ name: d[1], value: d[2].trim() })
    }
    if (decls.length) blocks.push({ selector, decls })
  }
  return blocks
}

function emit(selector, decls) {
  const lines = decls
    .filter((d) => !SKIP.has(d.name))
    .map((d) => `  --jcode-${d.name}: var(--${d.name}, ${d.value});`)
  return `${selector} {\n${lines.join('\n')}\n}\n`
}

const blocks = collectBlocks(src)
const light = blocks.find((b) => b.selector.startsWith('[data-jcode-ui]'))
const dark = blocks.find((b) => b.selector.startsWith('.dark'))

if (!light || !dark) {
  console.error('generate-compat-css: could not find token blocks in tokens.css')
  process.exit(1)
}

const header = `/* AUTO-GENERATED by scripts/generate-compat-css.mjs — do not edit.
 * Legacy token bridge: unprefixed pre-0.2 names → scoped --jcode-* tokens.
 * Load AFTER styles.css. */
`

mkdirSync(join(pkgRoot, 'dist'), { recursive: true })
writeFileSync(
  join(pkgRoot, 'dist/compat.css'),
  header + emit(LIGHT_SEL, light.decls) + '\n' + emit(DARK_SEL, dark.decls),
)
console.log(
  `compat.css: ${light.decls.length} light + ${dark.decls.length} dark tokens bridged`,
)
